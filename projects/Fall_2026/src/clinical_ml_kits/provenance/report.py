"""Generated verification log (``kits/<dataset>/<kit>/docs/verification_log.md``).

Rendered only from structured records: inline ProvenanceRefs and value states in kit.yaml and
phenotype.yaml, Deviations, the logical concepts used, and ``verification.yaml`` notes
(``documentation_derived | method_decision`` per item path; no status fields, P-11).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from clinical_ml_kits.core.values import (
    PROVISIONAL_BANNER,
    Provisional,
    Sourced,
    Unverified,
    iter_provenance,
)

HEADER = (
    "<!-- GENERATED by `ckit docs` from kit.yaml, phenotype.yaml, and verification.yaml. "
    "Do not edit by hand: CI runs `ckit docs --check`. -->"
)


def load_verification_notes(path: Path) -> dict[str, dict[str, str]]:
    """Read ``verification.yaml``; any status-like field is rejected (P-11)."""
    from clinical_ml_kits.provenance.checks import check_document, errors

    p = Path(path)
    if not p.is_file():
        return {}
    data = yaml.safe_load(p.read_text()) or {}
    bad = errors(check_document("verification_notes", data))
    if bad:
        raise ValueError("; ".join(str(f) for f in bad))
    items = data.get("items") or {}
    return {
        str(k): {"category": str(v.get("category", "")), "note": str(v.get("note", ""))}
        for k, v in items.items()
    }


def _fmt(v: Any) -> str:
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_fmt(x) for x in v) + "]"
    return str(v).replace("|", "\\|").replace("\n", " ")


def _states(kit: Any) -> list[tuple[str, Any]]:
    from clinical_ml_kits.core.kit_schema import _states as states

    return states(kit)


def render_verification_log(kit: Any, ctx: Any, notes: dict[str, dict[str, str]]) -> str:
    d, ph = kit.definition, kit.phenotype
    states = _states(kit)
    prov = [(p, v) for p, v in states if isinstance(v, Provisional)]
    unv = [(p, v) for p, v in states if isinstance(v, Unverified)]
    ver = [(p, v) for p, v in states if isinstance(v, Sourced)]
    L: list[str] = [HEADER, "", f"# Verification log — `{d.kit_id}`", ""]
    L += [
        f"- Kit status: **{d.status}** · kit version {d.kit_version} · phenotype "
        f"`{ph.id}` {ph.version} ({ph.status})",
        f"- Clinical values: {len(ver)} verified · {len(prov)} provisional · {len(unv)} unverified",
        "- Approval requires every value verified (FR-158, P-4); provisional values are for "
        "synthetic execution only.",
        "",
        "## Provisional values",
        "",
    ]
    if prov:
        L += [
            f"> **{PROVISIONAL_BANNER}**",
            "",
            "| Item | Provisional value | Pending | Note | Decision notes |",
            "|---|---|---|---|---|",
        ]
        for p, v in prov:
            n = notes.get(p, {})
            extra = f"{n['category']}: {n['note']}" if n else ""
            L.append(
                f"| `{p}` | {_fmt(v.provisional)} | {v.pending} | {_fmt(v.note)} | {_fmt(extra)} |"
            )
    else:
        L.append("None.")
    L += ["", "## Unverified items (UNVERIFIED / REQUIRES REVIEW)", ""]
    if unv:
        L += ["| Item | Decision notes |", "|---|---|"]
        for p, _ in unv:
            n = notes.get(p, {})
            L.append(f"| `{p}` | {_fmt(n.get('note', ''))} |")
    else:
        L.append("None.")
    L += ["", "## Verified values", ""]
    if ver:
        L += ["| Item | Value | Sources | Verified by | Verified on |", "|---|---|---|---|---|"]
        for p, sv in ver:
            vrefs = [r for r in sv.provenance if r.is_verified]
            L.append(
                f"| `{p}` | {_fmt(sv.value)} | {', '.join(r.source_id for r in vrefs)} | "
                f"{', '.join(sorted({str(r.verified_by) for r in vrefs}))} | "
                f"{', '.join(sorted({str(r.verified_on) for r in vrefs}))} |"
            )
    else:
        L.append("None.")
    L += [
        "",
        "## Provenance references",
        "",
        "| Location | Source | Status | Locator |",
        "|---|---|---|---|",
    ]
    all_refs = [*iter_provenance(d), *iter_provenance(ph, "phenotype")]
    for p, r in dict(all_refs).items():
        if ".provenance" in p and any(p.startswith(sp) for sp, _ in states):
            continue  # value-state refs are listed with their values above
        L.append(f"| `{p}` | {r.source_id} | {r.verification_status} | {_fmt(r.locator)} |")
    L += [
        "",
        "## Logical concepts used",
        "",
        "| Concept | Clinical-meaning provenance | `synthetic` realization | `omop` realization |",
        "|---|---|---|---|",
    ]
    from clinical_ml_kits.core.errors import PendingVerification
    from clinical_ml_kits.core.kit_schema import feature_concepts

    for c in sorted(kit.concepts() | set(feature_concepts(kit, ctx).values())):
        try:
            concept = ctx.concepts.concept(c)
            cstat = "verified" if any(r.is_verified for r in concept.provenance) else concept.status
        except KeyError:
            cstat = "MISSING"
        cells = []
        for ns in ("synthetic", "omop"):
            try:
                real = ctx.concepts.realization(ns, c)
                cells.append(
                    f"{real.version} ({'verified' if real.mapping_verified else real.status})"
                )
            except PendingVerification:
                cells.append("UNVERIFIED / REQUIRES REVIEW (none)" if ns == "omop" else "missing")
        L.append(f"| `{c}` | {cstat} | {cells[0]} | {cells[1]} |")
    L += ["", "## Deviations from official definitions", ""]
    devs = list(ph.deviations)
    if devs:
        L += [
            "| Item | Official definition | Deviation | Reason | Expected impact |",
            "|---|---|---|---|---|",
        ]
        for dv in devs:
            L.append(
                f"| `{dv.item}` | {_fmt(dv.official_definition)} | {_fmt(dv.deviation)} | "
                f"{_fmt(dv.reason)} | {_fmt(dv.expected_impact)} |"
            )
    else:
        L.append("None recorded.")
    L += ["", "## Decision notes (verification.yaml)", ""]
    if notes:
        L += ["| Item | Category | Note |", "|---|---|---|"]
        for k in sorted(notes):
            L.append(f"| `{k}` | {notes[k]['category']} | {_fmt(notes[k]['note'])} |")
    else:
        L.append("None.")
    return "\n".join(L) + "\n"


def log_path(kit: Any) -> Path:
    return Path(kit.kit_dir) / kit.definition.docs / "verification_log.md"


def render_for_kit(kit: Any, ctx: Any) -> str:
    return render_verification_log(
        kit, ctx, load_verification_notes(Path(kit.kit_dir) / "verification.yaml")
    )
